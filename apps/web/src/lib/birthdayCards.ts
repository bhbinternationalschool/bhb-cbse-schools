export function normalizeBirthdaySettings(raw: unknown): BirthdaySettings {
  const d = defaultBirthdaySettings();
  if (!raw || typeof raw !== "object") return d;
  const r = raw as Partial<BirthdaySettings>;
  return {
    version: 1,
    design: normalizeDesign(r.design),
    format: normalizeFormat(r.format),
    cardWish: str(r.cardWish, 120),
    messageEn: str(r.messageEn, 1000),
    messageHi: str(r.messageHi, 1000),
    // Only an explicit "en" is English; anything else is the school default.
    // It read `=== "hi" ? "hi" : "en"`, so a missing value meant English.
    defaultLanguage: r.defaultLanguage === "en" ? "en" : r.defaultLanguage === "hi" ? "hi" : SCHOOL_DEFAULT_WA_LANGUAGE,
    autoSend: r.autoSend === true,
    staffEnabled: r.staffEnabled === true,
    staffMessageEn: str(r.staffMessageEn, 1000),
    staffMessageHi: str(r.staffMessageHi, 1000),
    staffWaTemplateName: str(r.staffWaTemplateName, 120),
    staffWaTemplateLanguage: str(r.staffWaTemplateLanguage, 10),
    staffWaTemplateVars: Array.isArray(r.staffWaTemplateVars) ? r.staffWaTemplateVars.map((x) => str(x, 30)).filter(Boolean).slice(0, 8) : [],
    directorName: str(r.directorName, 80),
    principalName: str(r.principalName, 80),
    sendHour: Number.isInteger(Number(r.sendHour)) && Number(r.sendHour) >= 0 && Number(r.sendHour) <= 23 ? Number(r.sendHour) : 9,
    waTemplateName: str(r.waTemplateName, 120),
    waTemplateLanguage: str(r.waTemplateLanguage, 10),
    waTemplateVars: Array.isArray(r.waTemplateVars) ? r.waTemplateVars.map((x) => str(x, 30)).filter(Boolean).slice(0, 8) : [],
    socialEnabled: r.socialEnabled === true,
    socialIncludePhoto: r.socialIncludePhoto === true,
    socialCaption: str(r.socialCaption, 600),
    socialDesign: normalizeDesign(r.socialDesign ?? "minimal"),
    updatedAt: str(r.updatedAt, 40),
  };
}

export function normalizeBirthdayState(raw: unknown): BirthdayState {
  const r = (raw ?? {}) as Partial<BirthdayState>;
  const seen = new Set<string>();
  const log: BirthdayLogEntry[] = [];
  for (const e of Array.isArray(r.log) ? r.log : []) {
    const x = (e ?? {}) as Partial<BirthdayLogEntry>;
    const key = str(x.key, 80);
    if (!key || seen.has(key + String(x.channel))) continue;
    seen.add(key + String(x.channel));
    log.push({
      key,
      subjectId: str(x.subjectId ?? (x as { studentId?: string }).studentId, 40),
      subject: x.subject === "staff" ? "staff" : "student",
      date: str(x.date, 10),
      channel: x.channel === "social" || x.channel === "manual" ? x.channel : "whatsapp",
      status: x.status === "failed" || x.status === "deferred" || x.status === "skipped" ? x.status : "sent",
      detail: str(x.detail, 200),
      at: str(x.at, 40),
    });
  }
  return { settings: normalizeBirthdaySettings(r.settings), log: log.slice(-LOG_MAX) };
}

export function emptyBirthdayState(): BirthdayState {
  return { settings: defaultBirthdaySettings(), log: [] };
}

export function loadBirthdayState(): BirthdayState {
  if (typeof window === "undefined") return emptyBirthdayState();
  try {
    const raw = window.localStorage.getItem(STORAGE_KEY);
    return raw ? normalizeBirthdayState(JSON.parse(raw)) : emptyBirthdayState();
  } catch {
    return emptyBirthdayState();
  }
}

export function saveBirthdayState(state: BirthdayState): BirthdayState {
  const next = normalizeBirthdayState({ ...state, settings: { ...state.settings, updatedAt: new Date().toISOString() } });
  if (!assertModulePermission("students", "edit", "saveBirthdayState")) return next;
  if (typeof window !== "undefined") {
    writeCacheOrInvalidate(STORAGE_KEY, JSON.stringify(next));
    void trackServerWork(import("@/lib/localModulesPersistence").then((m) => m.scheduleModuleStateSync("birthday_settings", next)));
    window.dispatchEvent(new CustomEvent("bhb-birthday-settings"));
  }
  return next;
}

export function writeBirthdayStateLocalRaw(state: BirthdayState): void {
  if (typeof window === "undefined") return;
  try {
    writeCacheOrInvalidate(STORAGE_KEY, JSON.stringify(normalizeBirthdayState(state)));
  } catch {
    /* quota */
  }
  window.dispatchEvent(new CustomEvent("bhb-birthday-settings"));
}

export function birthdayStateIsEmpty(s: BirthdayState): boolean {
  return !s.settings.updatedAt && s.log.length === 0;
}

/** Merge-safe log append (server and client both write; union by key+channel, newest wins). */
export function appendBirthdayLog(state: BirthdayState, entries: BirthdayLogEntry[]): BirthdayState {
  const map = new Map(state.log.map((e) => [`${e.key}|${e.channel}`, e]));
  for (const e of entries) map.set(`${e.key}|${e.channel}`, e);
  return { ...state, log: [...map.values()].sort((a, b) => a.at.localeCompare(b.at)).slice(-LOG_MAX) };
}

export function alreadySent(
  state: BirthdayState,
  subjectId: string,
  date: string,
  channel: BirthdayLogEntry["channel"],
  subject: BirthdaySubject = "student",
): boolean {
  return state.log.some((e) => e.subjectId === subjectId && e.subject === subject && e.date === date && e.channel === channel && e.status === "sent");
}

/** The text for one family. */
export function birthdayMessageFor(opts: {
  settings: BirthdaySettings;
  language: BirthdayMessageLanguage;
  childName: string;
  guardianName: string;
  className: string;
  age: number | null;
  schoolName: string;
  cardLink: string;
}): string {
  const custom = opts.language === "hi" ? opts.settings.messageHi : opts.settings.messageEn;
  const template = custom || DEFAULT_BIRTHDAY_MESSAGES[opts.language][0].body;
  const firstName = (opts.childName || "").split(/\s+/)[0] || opts.childName;
  return renderBirthdayMessage(template, {
    childName: opts.childName,
    firstName,
    guardianName: opts.guardianName || (opts.language === "hi" ? "अभिभावक" : "Parent"),
    className: opts.className,
    age: opts.age != null ? String(opts.age) : "",
    schoolName: opts.schoolName,
    cardLink: opts.cardLink,
  });
}

