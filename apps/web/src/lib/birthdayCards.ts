export function staffBirthdayMessageFor(opts: {
  settings: BirthdaySettings;
  language: BirthdayMessageLanguage;
  name: string;
  designation: string;
  age: number | null;
  schoolName: string;
  cardLink: string;
}): string {
  const custom = opts.language === "hi" ? opts.settings.staffMessageHi : opts.settings.staffMessageEn;
  const template = custom || DEFAULT_STAFF_BIRTHDAY_MESSAGES[opts.language][0].body;
  const firstName = (opts.name || "").split(/\s+/)[0] || opts.name;
  return renderBirthdayMessage(template, {
    name: opts.name,
    firstName,
    designation: opts.designation,
    age: opts.age != null ? String(opts.age) : "",
    schoolName: opts.schoolName,
    cardLink: opts.cardLink,
  });
}

/**
 * The line printed at the foot of the card. The school's name is already in
 * the card header, so this carries only the person and their office — and it
 * is never blank, because a card that thanks somebody on the school's behalf
 * should say who from.
 */
export function birthdayCardSignature(settings: BirthdaySettings, subject: BirthdaySubject): string {
  const office = subject === "staff" ? "Director" : "Principal";
  const name = (subject === "staff" ? settings.directorName : settings.principalName).trim();
  const lead = subject === "staff" ? "With warm regards" : "With warm wishes";
  return `${lead} — ${[name, office].filter(Boolean).join(", ")}`;
}
