export type BirthdayStudentLike = { id: string; fullName: string; dob: string; status?: string; classId?: string; sectionId?: string; householdId?: string; photoUrl?: string; admissionNo?: string; academicYearCode?: string };

/**
 * SIS keeps one row per student per session; the same child must count once.
 * Key = admission no (fallback name+dob), keep the row with the latest
 * session code (ties → the one with a photo).
 */
export function dedupeStudents<T extends BirthdayStudentLike>(students: T[]): T[] {
  const best = new Map<string, T>();
  for (const s of students) {
    const key = (s.admissionNo || "").trim() || `${s.fullName.trim().toLowerCase()}|${s.dob}`;
    const cur = best.get(key);
    if (!cur) {
      best.set(key, s);
      continue;
    }
    const a = s.academicYearCode || "";
    const b = cur.academicYearCode || "";
    if (a > b || (a === b && !cur.photoUrl && !!s.photoUrl)) best.set(key, s);
  }
  return [...best.values()];
}

/** "YYYY-MM-DD" → "MM-DD"; invalid → "" */
export function monthDay(ymd: string): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec((ymd || "").slice(0, 10));
  return m ? `${m[2]}-${m[3]}` : "";
}

/** Students whose birthday falls on `dateYmd` (29-Feb birthdays count on 28-Feb in non-leap years). */
export function studentsWithBirthday<T extends BirthdayStudentLike>(
  students: T[],
  dateYmd: string,
  /**
   * The running session. Omit it and children who have left are greeted
   * forever — their row stays "active" and nothing else removes them.
   */
  sessionAy?: string,
): T[] {
  const md = monthDay(dateYmd);
  if (!md) return [];
  const year = Number(dateYmd.slice(0, 4));
  const leap = (year % 4 === 0 && year % 100 !== 0) || year % 400 === 0;
  // dedupeStudents already stops a double send, but nothing removed a child
  // who has LEFT: their row stays "active" forever, so an ex-parent received
  // a birthday template and card link from the school every year, at a
  // template charge each.
  return dedupeStudents(
    students.filter(
      (s) =>
        (s.status ?? "active") === "active" &&
        (!sessionAy || !s.academicYearCode || s.academicYearCode === sessionAy),
    ),
  )
    .filter((s) => {
      const b = monthDay(s.dob);
      if (!b) return false;
      if (b === md) return true;
      return b === "02-29" && md === "02-28" && !leap;
    })
    .sort((a, b) => a.fullName.localeCompare(b.fullName));
}

/* ─── Staff birthdays ──────────────────────────────────────────────── */

/**
 * The staff fields a birthday needs. A staff member is their own recipient —
 * there is no household, no guardian and no language preference behind them,
 * so the school default language applies and quiet hours do not.
 */
export type BirthdayStaffLike = {
  id: string;
  fullName: string;
  dateOfBirth: string;
  status?: string;
  designationId?: string | null;
  mobile?: string;
  altMobile?: string;
  photoUrl?: string;
};

/** Does a date of birth fall on `dateYmd`? (29-Feb counts on 28-Feb in non-leap years.) */
export function birthdayFallsOn(dob: string, dateYmd: string): boolean {
  const md = monthDay(dateYmd);
  const b = monthDay(dob);
  if (!md || !b) return false;
  if (b === md) return true;
  const year = Number(dateYmd.slice(0, 4));
  const leap = (year % 4 === 0 && year % 100 !== 0) || year % 400 === 0;
  return b === "02-29" && md === "02-28" && !leap;
}

/** Active staff whose birthday falls on `dateYmd`. */
export function staffWithBirthday<T extends BirthdayStaffLike>(staff: T[], dateYmd: string): T[] {
  if (!monthDay(dateYmd)) return [];
  return staff
    .filter((x) => (x.status ?? "active") === "active" && birthdayFallsOn(x.dateOfBirth, dateYmd))
    .sort((a, b) => a.fullName.localeCompare(b.fullName));
}

/** Upcoming staff birthdays within `days` from `fromYmd` (inclusive). */
export function upcomingStaffBirthdays<T extends BirthdayStaffLike>(staff: T[], fromYmd: string, days: number): { date: string; member: T; age: number | null }[] {
  const out: { date: string; member: T; age: number | null }[] = [];
  const start = new Date(`${fromYmd}T00:00:00`);
  for (let i = 0; i < days; i++) {
    const d = new Date(start);
    d.setDate(start.getDate() + i);
    const ymd = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
    for (const m of staffWithBirthday(staff, ymd)) out.push({ date: ymd, member: m, age: ageOn(m.dateOfBirth, ymd) });
  }
  return out;
}

/** Upcoming birthdays within `days` from `fromYmd` (inclusive), with the date they fall on. */
export function upcomingBirthdays<T extends BirthdayStudentLike>(students: T[], fromYmd: string, days: number): { date: string; student: T; age: number | null }[] {
  const out: { date: string; student: T; age: number | null }[] = [];
  const start = new Date(`${fromYmd}T00:00:00`);
  for (let i = 0; i < days; i++) {
    const d = new Date(start);
    d.setDate(start.getDate() + i);
    const ymd = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
    for (const s of studentsWithBirthday(students, ymd)) out.push({ date: ymd, student: s, age: ageOn(s.dob, ymd) });
  }
  return out;
}

export function ageOn(dob: string, ymd: string): number | null {
  const by = Number((dob || "").slice(0, 4));
  const y = Number(ymd.slice(0, 4));
  if (!by || !y || by > y) return null;
  return y - by;
}

