/**
 * Birthday cards & greetings — the pure part.
 *
 *  - Who: active students whose DOB (month-day) matches a date, and — when
 *    the school turns it on — active staff whose own date of birth does.
 *    A student's greeting goes to the FAMILY; a staff member's goes to them.
 *  - Card: one of several designs × formats (square for WhatsApp/Instagram,
 *    story, landscape for Facebook, A5 portrait for print), rendered server-side
 *    by /api/birthday/card (next/og). The design + format choice lives here;
 *    the drawing lives in birthdayCardDesigns.tsx.
 *  - Message: templates per language with placeholders, editable by the
 *    school; rendered with the family's own details. Nothing is generated by
 *    a model — a birthday wish has no facts to get wrong and must be instant.
 *  - Settings (module_local_state "birthday_settings"): chosen design/format,
 *    message templates, auto-send on/off + hour, staff greetings on/off and
 *    their own templates, who signs the card, the WhatsApp template for
 *    outside-24h delivery, social posting (off by default, photos only on
 *    explicit opt-in), and a send log keyed by subject+date so a day is never
 *    sent twice.
 */

